fun getDictionary(languageCode: String): TranslationDictionary {
    return when (AppLanguage.fromCode(languageCode)) {
        AppLanguage.ENGLISH -> EnglishDictionary
        AppLanguage.MYANMAR -> MyanmarDictionary
        AppLanguage.THAI -> ThaiDictionary
    }
}

